'use strict';
const fs=require('node:fs');
const cp=require('node:child_process');
const assert=require('node:assert/strict');
const branch=cp.execFileSync('git',['branch','--show-current'],{encoding:'utf8'}).trim();
assert.equal(branch,'feature/universal-claims-v2026-09-17-1430','Feature branch only');
const path='index.html';
assert.equal(cp.execFileSync('git',['hash-object',path],{encoding:'utf8'}).trim(),'31813caf55610c7cae0889b1908a54e4e939ca08','Unexpected index version; inspect before editing');
const html=fs.readFileSync(path,'utf8');
const tail='<script src="./src/universal-dashboard-navigation.js"></script>\n</body>\n</html>';
assert.equal(html.split(tail).length,2,'Expected exactly one known HTML tail');
assert.doesNotMatch(html,/src="\.\/src\/universal-admin-delete\.js"/);
assert.match(html,/function loadMyRequests\(\)/);
assert.match(html,/\.select\('can_submit,can_approve,can_view,can_mark_paid,is_admin'\)/);
assert.match(html,/onclick="openReview\('\$\{r\.id\}'\)"/);
assert.match(fs.readFileSync('src/universal-admin-delete.js','utf8'),/meg_forms_admin_delete_claim/);
const patched=html.replace(tail,'<script src="./src/universal-dashboard-navigation.js"></script>\n<script src="./src/universal-admin-delete.js"></script>\n</body>\n</html>');
assert.notEqual(patched,html);
assert.equal((patched.match(/src="\.\/src\/universal-admin-delete\.js"/g)||[]).length,1);
fs.writeFileSync(path,patched);
console.log('PRFAF Admin Delete wired exactly once on feature branch; no direct table deletes, approvals or ledger changes');
