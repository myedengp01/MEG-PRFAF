'use strict';
const fs = require('node:fs');
const cp = require('node:child_process');
const assert = require('node:assert/strict');
const branch = cp.execFileSync('git', ['branch', '--show-current'], {encoding:'utf8'}).trim();
assert.equal(branch, 'feature/universal-claims-v2026-09-17-1430', 'Never modify main');
const path = 'index.html';
const originalBlob = cp.execFileSync('git', ['hash-object', path], {encoding:'utf8'}).trim();
assert.equal(originalBlob, '602ddc07a5af468ba0021d00dd37d4c163da42ac', 'Unexpected index version; inspect and rebase before editing');
const html = fs.readFileSync(path, 'utf8');
const ending = '</script>\n</body>\n</html>';
assert.equal(html.split(ending).length, 2, 'Expected one unmodified script/body tail');
assert.match(html, /<a class="dash-link" href="https:\/\/myedengp01\.github\.io\/DB-MEG-FORMS\/">← Dashboard<\/a>/);
assert.doesNotMatch(html, /src="\.\/src\/universal-dashboard-navigation\.js"/);
const patched = html.replace(ending, '</script>\n<script src="./src/universal-dashboard-navigation.js"></script>\n</body>\n</html>');
assert.notEqual(patched, html);
fs.writeFileSync(path, patched);
assert.equal((patched.match(/src="\.\/src\/universal-dashboard-navigation\.js"/g)||[]).length,1);
console.log('PRFAF navigation module wired once, feature branch only; no auth, payment or ledger changes');
